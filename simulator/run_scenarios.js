// Runs every predefined scenario against the C controller without a browser,
// with the same map logic as the web page, and writes:
//   artifacts/SystemTest/traces/<id>.json   the complete tick-by-tick trace
//   artifacts/SystemTest/execution_summary.md   what happened, in short
// It assigns no PASS or FAIL. The human evaluator does that in the simulator.
//
//   node simulator/run_scenarios.js
'use strict';

const fs = require('fs');
const path = require('path');
const World = require('./public/world');
const { SCENARIOS } = require('./public/scenarios');
const { ControllerProcess } = require('./controller_process');

const OUT_DIR = process.env.RVC_SCENARIO_OUT || path.join(__dirname, '..', 'artifacts', 'SystemTest');

// Runs one scenario for the full 100 ticks. Returns the list of snapshots.
async function runScenario(controller, scenario) {
    const problems = World.validate(scenario);
    if (problems.length > 0) {
        throw new Error(`${scenario.id}: ${problems.join(' ')}`);
    }
    const world = World.create(scenario);
    const power_on = await controller.start(World.sense(world));
    const history = [{ ...power_on, events: [], world: World.snapshot(world) }];
    for (let tick = 1; tick <= World.MAX_TICKS; tick++) {
        const sensors = World.sense(world);
        const result = await controller.step(sensors);
        const events = World.apply(world, result.direction, result.clean);
        history.push({ ...result, events, world: World.snapshot(world) });
    }
    return history;
}

// "Forward/Start 1-4, Stop/Stop 5-9, ..." for a history.
function commandRuns(history) {
    const runs = [];
    history.slice(1).forEach((snap) => {
        const label = `${snap.direction}/${snap.clean}`;
        const last = runs[runs.length - 1];
        if (last && last.label === label) {
            last.to = snap.tick;
        } else {
            runs.push({ label, from: snap.tick, to: snap.tick });
        }
    });
    return runs.map((run) => `${run.label} ${run.from}${run.to > run.from ? '-' + run.to : ''}`);
}

async function main() {
    fs.mkdirSync(path.join(OUT_DIR, 'traces'), { recursive: true });
    const controller = new ControllerProcess();
    let summary = '# Scenario Execution Summary\n\n' +
        'Generated by `node simulator/run_scenarios.js`. Each scenario ran for 100 ticks against the C controller.\n' +
        'Each entry lists Direction/Clean with the ticks it was issued on. This is a record of what happened, not a verdict.\n\n';
    for (const scenario of SCENARIOS) {
        const history = await runScenario(controller, scenario);
        fs.writeFileSync(path.join(OUT_DIR, 'traces', `${scenario.id}.json`),
            JSON.stringify({ scenario, history }, null, 1));
        const last = history[history.length - 1];
        const runs = commandRuns(history);
        const shown = runs.length > 14 ? runs.slice(0, 14).join(', ') + `, ... (${runs.length} runs)` : runs.join(', ');
        summary += `## ${scenario.id} ${scenario.name}\n\n` +
            `- Commands: ${shown}\n` +
            `- Position after tick 100: (${last.world.x},${last.world.y}) heading ${last.world.heading}, controller state ${last.state}\n` +
            `- Dust left: ${last.world.dust.length === 0 ? 'none' : last.world.dust.map((d) => '(' + d + ')').join(' ')}\n\n`;
        console.log(`${scenario.id} ${scenario.name}: ${runs.slice(0, 8).join(', ')}`);
    }
    controller.stop();
    fs.writeFileSync(path.join(OUT_DIR, 'execution_summary.md'), summary);
}

main().catch((err) => {
    console.error(err.message || err);
    process.exit(1);
});
